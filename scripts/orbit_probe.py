#!/usr/bin/env python3
"""Decide the *multiplier-invariant* circulant colourings — a smaller sub-family.

A circulant colouring assigns a colour to every difference class of ``Z_n``.
Multiplying all vertices by a unit ``u`` (``gcd(u, n) = 1``) conjugates one
circulant colouring into another: class ``d`` moves to class ``u·d``.  Asking the
colouring to be invariant under that group means the colour depends only on the
*orbit* of the class, which collapses the instance — one variable per
(orbit, colour) instead of one per (class, colour).  For the target sizes that is
21 variables for ``K128`` (7 orbits, 3 colours) against 192, and ``K161`` drops
from 400 to 15.

    multiplier-invariant colourings  ⊊  circulant colourings  ⊊  all colourings

The chain matters in both directions:

* a model of the reduced CNF is a genuine clean **circulant** colouring, so a
  witness found here is a witness as the repository already verifies it
  (:func:`oplab.multicolour.verify_colouring` re-counts every clique — no new claim
  kind), and at a published-witness size it would raise the bound;
* UNSAT here is *weaker* than UNSAT for the whole circulant family: it says the
  structured candidates are empty, not that the family is.  This script never
  reports one as the other.

The reduction is a substitution, not a heuristic: ``x[class][colour]`` is replaced
by ``y[orbit][colour]`` in the instance's own clauses, which is why the encoding is
built from :class:`oplab.multicolour.CirculantInstance` rather than re-derived.

Usage::

    python scripts/orbit_probe.py 96:3,3,3,4 128:4,4,4 --json out.json

    K96 (3, 3, 3, 4): UNSAT (48 classes -> 11 orbits, 44 vars, 20086 clauses)
    K128 (4, 4, 4): UNSAT (64 classes -> 7 orbits, 21 vars, 127585 clauses)

Measured 2026-10-16.  The full unit group is empty at all six undecided target
sizes (``K96``, ``K97``, ``K127``, ``K128``, ``K161``, ``K538``), while ``K8`` with
sizes ``(3,3,3)`` is SAT and yields a verified witness — which is what keeps the
negative meaningful.  But the full group is *too strong* a restriction, so
``--by-subgroup`` decides every distinct subgroup (5 to 16 per size) and the answer
depends on the size: ``K127`` ``(4,4,4)`` is **SAT in 2 s** at the order-42 subgroup
(3 orbits, 9 variables) with a witness the verifier re-counts — at the published
witness size, so not a record — while ``K96``, ``K97`` and ``K161`` are UNSAT in
every *genuine* subgroup down to the ones that coincide with the full instance, and
``K537`` is UNSAT everywhere by the arithmetic obstruction.

``--canonical`` adds the other symmetry: colours with the same forbidden clique size
are interchangeable, so requiring them to *first appear* in increasing order costs no
colouring (a factor ``3!``, ``5!`` or ``6!`` of search space).  ``--compare`` is the
soundness check for it — both encodings run on every subgroup of a case, and the
verdicts must agree, with every ``sat`` row re-counted clean.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from oplab import multicolour as MC  # noqa: E402


def unit_group(n: int) -> list[int]:
    """Every unit of ``Z_n``, i.e. every ``u`` with ``gcd(u, n) = 1``."""
    return [u for u in range(1, n) if math.gcd(u, n) == 1]


def subgroups(n: int) -> list[list[int]]:
    """Every *distinct* subgroup of the unit group, in element-tuple order.

    A subgroup of order ``m`` leaves roughly ``classes/m`` orbits, so the smaller
    the subgroup the larger — and the more hopeful — the family it decides; the
    sweeps sort these by size for exactly that reason.
    """
    found: dict[tuple[int, ...], None] = {}
    for u in unit_group(n):
        found.setdefault(tuple(subgroup(n, [u])), None)
    return [list(h) for h in sorted(found)]


def subgroup(n: int, generators) -> list[int]:
    """The subgroup generated by the given units, as its element list."""
    seen = {1}
    frontier = [1]
    steps = [g % n for g in generators]
    while frontier:
        x = frontier.pop()
        for g in steps:
            y = (x * g) % n
            if y not in seen:
                seen.add(y)
                frontier.append(y)
    return sorted(seen)


def orbits(n: int, units=None) -> list[list[int]]:
    """The difference classes grouped by the orbit of the given group's action.

    ``units=None`` means the whole unit group, which is the tightest restriction
    and therefore the smallest instance; a subgroup gives a larger family — more
    orbits, more freedom — that is still a family of genuine circulant colourings.
    """
    classes = MC.difference_classes(n)
    units = unit_group(n) if units is None else list(units)
    parent = {d: d for d in classes}

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for d in classes:
        for u in units:
            a, b = find(d), find(MC.difference_class(u * d, n))
            if a != b:
                parent[a] = b
    grouped: dict[int, list[int]] = {}
    for d in classes:
        grouped.setdefault(find(d), []).append(d)
    return [grouped[key] for key in sorted(grouped)]


def reduced(n: int, sizes, units=None, colour_canonical: bool = False):
    """``(instance, orbits, class->orbit, clauses)`` for the invariant sub-family.

    With ``colour_canonical`` the encoding is also required to use colours of
    equal forbidden-clique size *in order of first appearance*: the colour of
    rank ``r`` inside its size class may appear at an orbit only if a lower-rank
    colour of the same class already appeared earlier.  That is a relabelling —
    swap the equal-size colours so that the first appearances come out ordered —
    so it costs no colourings, not one.  Colours of *different* sizes are not
    interchangeable and are left alone, which is why the break is stated inside
    the size classes rather than over all ``k`` colours.
    """
    instance = MC.CirculantInstance(n, sizes)
    groups = orbits(n, units)
    index = {d: i for i, group in enumerate(groups) for d in group}
    k = len(sizes)

    def var(i: int, colour: int) -> int:
        return i * k + colour + 1

    clauses: list[tuple[int, ...]] = []
    for i in range(len(groups)):
        clauses.append(tuple(var(i, c) for c in range(k)))
        for a in range(k):
            for b in range(a + 1, k):
                clauses.append((-var(i, a), -var(i, b)))
    if colour_canonical:
        by_size: dict[int, list[int]] = {}
        for colour, s in enumerate(sizes):
            by_size.setdefault(s, []).append(colour)
        for group_of_colours in by_size.values():
            same = sorted(group_of_colours)
            for rank, colour in enumerate(same[1:], start=1):
                for i in range(len(groups)):
                    literals = [-var(i, colour)]
                    for earlier in same[:rank]:
                        literals.extend(var(j, earlier) for j in range(i))
                    clauses.append(tuple(literals))
    for colour, s in enumerate(sizes):
        for group in instance.groups[s]:
            literals: list[int] = []
            for d in group:
                lit = -var(index[d], colour)
                # one orbit can hold several classes of a clique, in which case the
                # substitution shortens the clause instead of duplicating a literal
                if lit not in literals:
                    literals.append(lit)
            clauses.append(tuple(literals))
    return instance, groups, index, clauses


def solve(n: int, sizes, solver: str = "cadical195", units=None,
          colour_canonical: bool = False) -> dict:
    """Decide the invariant sub-family of one instance, expanding any witness."""
    instance, groups, index, clauses = reduced(n, sizes, units, colour_canonical)
    started = time.time()
    from pysat.solvers import Cadical195

    if solver != "cadical195":
        raise SystemExit("only cadical195 is used here: the bundled Kissat wheel dies "
                         "with an access violation on this platform")
    with Cadical195(bootstrap_with=clauses) as engine:
        engine.solve_limited(expect_interrupt=True)
        model = engine.get_model()
    result = {
        "n": n,
        "sizes": list(sizes),
        "classes": len(instance.classes),
        "group_order": len(unit_group(n) if units is None else units),
        "orbits": len(groups),
        "orbit_sizes": sorted(len(group) for group in groups),
        "vars": len(groups) * len(sizes),
        "clauses": len(clauses),
        "colour_canonical": bool(colour_canonical),
        "status": "sat" if model else "unsat",
        "seconds": round(time.time() - started, 3),
    }
    if not model:
        # weaker than the whole family's UNSAT, and the summary says so
        result["establishes"] = None
        return result
    truth = {lit for lit in model if lit > 0}
    colour_of: dict[int, int] = {}
    for i, group in enumerate(groups):
        chosen = [c for c in range(len(sizes)) if i * len(sizes) + c + 1 in truth]
        if len(chosen) != 1:
            raise ValueError(f"orbit {i} is not assigned exactly one colour")
        for d in group:
            colour_of[d] = chosen[0]
    text = MC.serialize_colouring(MC.circulant_colouring(n, colour_of), n)
    result["colouring"] = text
    result["verify"] = MC.verify_colouring(n, sizes, text)
    result["establishes"] = result["verify"]["establishes"]
    return result


def compare(n: int, sizes, solver: str = "cadical195", seconds: float = 60.0) -> list[dict]:
    """Run the plain and the colour-canonical encoding on the *same* families.

    Soundness of the break is exactly this: on every family where both runs reach
    a verdict, the verdicts agree, and every ``sat`` row of the broken encoding is
    re-counted clean.  Disagreement would mean the relabelling argument is wrong.
    """
    rows = []
    for h in sorted(subgroups(n), key=len, reverse=True):
        plain = solve_with_budget(n, sizes, h, solver=solver, seconds=seconds,
                                  colour_canonical=False)
        canon = solve_with_budget(n, sizes, h, solver=solver, seconds=seconds,
                                  colour_canonical=True)
        decided = (plain["status"], canon["status"])
        agree = plain["status"] == canon["status"] or "unknown" in decided
        row = {
            "n": n,
            "sizes": list(sizes),
            "subgroup_order": len(h),
            # a killed run has no summary, so take the size from whichever run has one
            "vars": canon.get("vars") or plain.get("vars"),
            "plain": plain["status"],
            "canonical": canon["status"],
            "agree": agree,
            "clean": canon.get("verify", {}).get("valid") if canon["status"] == "sat" else None,
            "establishes": canon.get("establishes"),
        }
        rows.append(row)
        print(f"K{n} {sizes} ord {len(h):>4} {row['vars']}v: plain={row['plain']:<8} "
              f"canonical={row['canonical']:<8} agree={agree} clean={row['clean']}", flush=True)
        if canon["status"] == "sat":
            break
    return rows


def _run_worker(conn, n: int, sizes, solver: str, units, colour_canonical: bool = False) -> None:  # pragma: no cover
    """Solve one subgroup's reduced family in a child and send the summary back."""
    try:
        out = solve(n, sizes, solver=solver, units=units, colour_canonical=colour_canonical)
    except Exception as exc:  # pragma: no cover - diagnostic path
        out = {"status": "error", "reason": f"{exc.__class__.__name__}: {exc}"}
    try:
        conn.send(out)
    finally:
        conn.close()


def solve_with_budget(n: int, sizes, units, solver: str = "cadical195",
                      seconds: float = 60.0, colour_canonical: bool = False) -> dict:
    """Bound one run from outside: the bundled solvers hold the GIL, so a
    thread-based timer never fires and a process the parent can kill is the only
    honest budget (see the same note in ``oplab.multicolour``)."""
    import multiprocessing as mp

    ctx = mp.get_context("spawn")
    parent, child = ctx.Pipe(duplex=False)
    proc = ctx.Process(target=_run_worker,
                       args=(child, n, list(sizes), solver, list(units), colour_canonical),
                       daemon=True)
    started = time.time()
    proc.start()
    proc.join(max(0.5, float(seconds)))
    if proc.is_alive():
        proc.terminate()
        proc.join(10)
        if proc.is_alive() and hasattr(proc, "kill"):  # pragma: no cover - defensive
            proc.kill()
        parent.close()
        return {"status": "unknown", "budget_expired": True,
                "seconds": round(time.time() - started, 3)}
    if parent.poll(10):
        out = parent.recv()
        parent.close()
        out["seconds"] = round(time.time() - started, 3)
        return out
    parent.close()
    return {"status": "no_verdict", "exit_code": proc.exitcode,
            "seconds": round(time.time() - started, 3)}


def sweep(n: int, sizes, solver: str = "cadical195", seconds: float = 60.0,
          colour_canonical: bool = False) -> list[dict]:
    """Decide *every* subgroup-invariant sub-family, largest group first.

    Ordered by subgroup size, so the most restricted (smallest) family is settled
    first and the trivial subgroup — which *is* the full circulant family — comes
    last.  A model for any subgroup is a genuine circulant colouring, so a single
    ``sat`` with a clean colouring is a witness whatever the subgroup; only the
    full group's ``unsat`` is a statement, and the smaller subgroups' ``unsat``
    says nothing about the published bounds.  The sweep stops at the first
    witness, since that already decides the whole circulant family for that size.
    """
    runs = []
    for h in sorted(subgroups(n), key=len, reverse=True):
        result = solve_with_budget(n, sizes, units=h, solver=solver, seconds=seconds,
                                   colour_canonical=colour_canonical)
        # a killed run has no summary of its own, so the identity travels with it
        result.setdefault("n", n)
        result.setdefault("sizes", list(sizes))
        result["subgroup_order"] = len(h)
        runs.append(result)
        print(f"  subgroup of order {len(h):>4}: {result['status']:<9}"
              f" {result.get('orbits', '-')} orbits, {result.get('vars', '-')} vars,"
              f" {result['seconds']} s", flush=True)
        if result["status"] == "sat":
            break  # a witness for the whole circulant family: nothing left to gain
    return runs


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("spec", nargs="+", help="targets as n:s1,s2,...")
    parser.add_argument("--json", default=None, help="write the results here")
    parser.add_argument("--by-subgroup", action="store_true",
                        help="sweep every subgroup instead of only the full unit group")
    parser.add_argument("--seconds", type=float, default=60.0,
                        help="external budget per subgroup run (default 60 s)")
    parser.add_argument("--canonical", action="store_true",
                        help="also break the colour-naming symmetry: equal-size colours "
                             "must first appear in increasing order")
    parser.add_argument("--compare", action="store_true",
                        help="check that the colour-canonical encoding agrees with the "
                             "plain one family by family, and exit non-zero if it does not")
    args = parser.parse_args(argv)

    results = []
    for spec in args.spec:
        n_text, _, sizes_text = spec.partition(":")
        if not sizes_text:
            print(f"{spec}: expected n:s1,s2,...", file=sys.stderr)
            return 2
        n = int(n_text)
        sizes = tuple(int(s) for s in sizes_text.split(","))
        if args.compare:
            rows = compare(n, sizes, seconds=args.seconds)
            results.extend(rows)
            disagreements = [r for r in rows if not r["agree"] or r["clean"] is False]
            note = "agrees" if not disagreements else f"DISAGREES on {len(disagreements)} family(ies)"
            print(f"K{n} {sizes}: the canonical break {note}", flush=True)
            if disagreements:
                print(json.dumps(disagreements, indent=2), file=sys.stderr)
                return 1
            continue
        if args.by_subgroup:
            print(f"K{n} {sizes}: sweeping {len(subgroups(n))} subgroups "
                  f"({args.seconds:.0f} s each)", flush=True)
            runs = sweep(n, sizes, seconds=args.seconds, colour_canonical=args.canonical)
            results.extend(runs)
            won = [r for r in runs if r["status"] == "sat"]
            if won:
                print(f"K{n} {sizes}: SAT in the subgroup of order "
                      f"{won[0]['subgroup_order']}  -> {won[0]['establishes']}",
                      flush=True)
            else:
                print(f"K{n} {sizes}: no witness in any of the {len(runs)} subgroups "
                      f"(up to {max((r.get('orbits') or 0) for r in runs)} orbits)",
                      flush=True)
            continue
        result = solve(n, sizes, colour_canonical=args.canonical)
        results.append(result)
        note = ""
        if result["status"] == "sat":
            note = (f"  -> {result['establishes']}" if result["establishes"]
                    else "  -> NOT CLEAN (a bug, not a witness)")
        print(f"K{n} {sizes}: {result['status'].upper()}{note}   "
              f"[{result['classes']} classes -> {result['orbits']} orbits, "
              f"{result['vars']} vars, {result['clauses']} clauses, "
              f"{result['seconds']} s]", flush=True)
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
